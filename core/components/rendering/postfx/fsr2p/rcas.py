from __future__ import annotations
RCAS_FRAG = (
    "\n"
    + chr(35) + 'version 330 core\n'
    + 'uniform sampler2D u_rcas_input;\n'
    + 'uniform vec2 u_rcas_size;\n'
    + 'uniform float u_rcas_con;\n'
    + 'in vec2 v_uv;\n'
    + 'out vec4 frag_color;\n'
    + '\n'
    + 'vec3 load(ivec2 p) {\n'
    + '    p = clamp(p, ivec2(0), ivec2(u_rcas_size) - ivec2(1));\n'
    + '    return texelFetch(u_rcas_input, p, 0).rgb;\n'
    + '}\n'
    + '\n'
    + 'const float FSR_RCAS_LIMIT = (0.25 - (1.0 / 16.0));\n'
    + '\n'
    + 'void main() {\n'
    + '    ivec2 ip = ivec2(gl_FragCoord.xy);\n'
    + '    vec3 b = load(ip + ivec2(0, -1));\n'
    + '    vec3 d = load(ip + ivec2(-1, 0));\n'
    + '    vec3 e = load(ip);\n'
    + '    vec3 f = load(ip + ivec2(1, 0));\n'
    + '    vec3 h = load(ip + ivec2(0, 1));\n'
    + '\n'
    + '    float bR = b.r, bG = b.g, bB = b.b;\n'
    + '    float dR = d.r, dG = d.g, dB = d.b;\n'
    + '    float eR = e.r, eG = e.g, eB = e.b;\n'
    + '    float fR = f.r, fG = f.g, fB = f.b;\n'
    + '    float hR = h.r, hG = h.g, hB = h.b;\n'
    + '\n'
    + '    float bL = bB * 0.5 + (bR * 0.5 + bG);\n'
    + '    float dL = dB * 0.5 + (dR * 0.5 + dG);\n'
    + '    float eL = eB * 0.5 + (eR * 0.5 + eG);\n'
    + '    float fL = fB * 0.5 + (fR * 0.5 + fG);\n'
    + '    float hL = hB * 0.5 + (hR * 0.5 + hG);\n'
    + '\n'
    + '    float nz = 0.25 * bL + 0.25 * dL + 0.25 * fL + 0.25 * hL - eL;\n'
    + '    nz = clamp(abs(nz) / max(max(max(max(bL, dL), eL), fL) - min(min(min(min(bL, dL), eL), fL), hL), 1e-6), 0.0, 1.0);\n'
    + '    nz = -0.5 * nz + 1.0;\n'
    + '\n'
    + '    float mn4R = min(min(min(bR, dR), fR), hR);\n'
    + '    float mn4G = min(min(min(bG, dG), fG), hG);\n'
    + '    float mn4B = min(min(min(bB, dB), fB), hB);\n'
    + '    float mx4R = max(max(max(bR, dR), fR), hR);\n'
    + '    float mx4G = max(max(max(bG, dG), fG), hG);\n'
    + '    float mx4B = max(max(max(bB, dB), fB), hB);\n'
    + '\n'
    + '    float hitMinR = mn4R / max(4.0 * mx4R, 1e-4);\n'
    + '    float hitMinG = mn4G / max(4.0 * mx4G, 1e-4);\n'
    + '    float hitMinB = mn4B / max(4.0 * mx4B, 1e-4);\n'
    + '    float hitMaxR = (1.0 - mx4R) / max(4.0 * mn4R - 4.0, -3.999999);\n'
    + '    float hitMaxG = (1.0 - mx4G) / max(4.0 * mn4G - 4.0, -3.999999);\n'
    + '    float hitMaxB = (1.0 - mx4B) / max(4.0 * mn4B - 4.0, -3.999999);\n'
    + '\n'
    + '    float lobeR = max(-hitMinR, hitMaxR);\n'
    + '    float lobeG = max(-hitMinG, hitMaxG);\n'
    + '    float lobeB = max(-hitMinB, hitMaxB);\n'
    + '    float lobe = max(-FSR_RCAS_LIMIT, min(max(lobeR, max(lobeG, lobeB)), 0.0)) * u_rcas_con;\n'
    + '    lobe *= nz;\n'
    + '\n'
    + '    float rcpL = 1.0 / (4.0 * lobe + 1.0);\n'
    + '    vec3 pix = (lobe * (b + d + h + f) + e) * rcpL;\n'
    + '    frag_color = vec4(pix, 1.0);\n'
    + '}\n'
)
