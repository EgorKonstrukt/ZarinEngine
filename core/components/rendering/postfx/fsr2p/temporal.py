from __future__ import annotations
TEMPORAL_FRAG = (
    "\n"
    + chr(35) + 'version 330 core\n'
    + 'uniform sampler2D u_current;\n'
    + 'uniform sampler2D u_depth;\n'
    + 'uniform sampler2D u_velocity;\n'
    + 'uniform sampler2D u_history;\n'
    + 'uniform sampler2D u_reactive;\n'
    + 'uniform vec2 u_pixel;\n'
    + 'uniform vec2 u_size;\n'
    + 'uniform float u_stability;\n'
    + 'uniform float u_disocclusion;\n'
    + 'uniform float u_variance_gamma;\n'
    + 'uniform float u_has_velocity;\n'
    + 'uniform float u_has_reactive;\n'
    + 'uniform int u_has_history;\n'
    + 'uniform int u_has_reproj;\n'
    + 'uniform mat4 u_inv_view_proj;\n'
    + 'uniform mat4 u_prev_view_proj;\n'
    + 'in vec2 v_uv;\n'
    + 'out vec4 frag_color;\n'
    + '\n'
    + 'vec3 fsr2_rgb_to_ycocg(vec3 c) {\n'
    + '    return vec3(\n'
    + '        dot(c, vec3(0.25, 0.5, 0.25)),\n'
    + '        dot(c, vec3(0.5, 0.0, -0.5)),\n'
    + '        dot(c, vec3(-0.25, 0.5, -0.25))\n'
    + '    );\n'
    + '}\n'
    + '\n'
    + 'vec3 fsr2_ycocg_to_rgb(vec3 c) {\n'
    + '    float y = c.x;\n'
    + '    float co = c.y;\n'
    + '    float cg = c.z;\n'
    + '    return vec3(y + co - cg, y + cg, y - co - cg);\n'
    + '}\n'
    + '\n'
    + 'vec3 fsr2_clip_to_box(vec3 history, vec3 center, vec3 extents) {\n'
    + '    vec3 v = history - center;\n'
    + '    vec3 unit = v / max(extents, vec3(1e-5));\n'
    + '    float ma = max(unit.x, max(unit.y, unit.z));\n'
    + '    float mi = min(unit.x, min(unit.y, unit.z));\n'
    + '    float m = max(ma, -mi);\n'
    + '    return m > 1.0 ? center + v / m : history;\n'
    + '}\n'
    + '\n'
    + 'vec3 fsr2_history_catmull_rom(sampler2D tex, vec2 uv, vec2 texSize) {\n'
    + '    vec2 samplePos = uv * texSize;\n'
    + '    vec2 texPos1 = floor(samplePos - 0.5) + 0.5;\n'
    + '    vec2 f = samplePos - texPos1;\n'
    + '    vec2 w0 = f * (-0.5 + f * (1.0 - 0.5 * f));\n'
    + '    vec2 w1 = 1.0 + f * f * (-2.5 + 1.5 * f);\n'
    + '    vec2 w2 = f * (0.5 + f * (2.0 - 1.5 * f));\n'
    + '    vec2 w3 = f * f * (-0.5 + 0.5 * f);\n'
    + '    vec2 w12 = w1 + w2;\n'
    + '    vec2 offset12 = w2 / max(w12, vec2(1e-5));\n'
    + '    vec2 texPos0 = (texPos1 - 1.0) / texSize;\n'
    + '    vec2 texPos3 = (texPos1 + 2.0) / texSize;\n'
    + '    vec2 texPos12 = (texPos1 + offset12) / texSize;\n'
    + '    vec3 result = vec3(0.0);\n'
    + '    result += texture(tex, vec2(texPos0.x, texPos0.y)).rgb * w0.x * w0.y;\n'
    + '    result += texture(tex, vec2(texPos12.x, texPos0.y)).rgb * w12.x * w0.y;\n'
    + '    result += texture(tex, vec2(texPos3.x, texPos0.y)).rgb * w3.x * w0.y;\n'
    + '    result += texture(tex, vec2(texPos0.x, texPos12.y)).rgb * w0.x * w12.y;\n'
    + '    result += texture(tex, vec2(texPos12.x, texPos12.y)).rgb * w12.x * w12.y;\n'
    + '    result += texture(tex, vec2(texPos3.x, texPos12.y)).rgb * w3.x * w12.y;\n'
    + '    result += texture(tex, vec2(texPos0.x, texPos3.y)).rgb * w0.x * w3.y;\n'
    + '    result += texture(tex, vec2(texPos12.x, texPos3.y)).rgb * w12.x * w3.y;\n'
    + '    result += texture(tex, vec2(texPos3.x, texPos3.y)).rgb * w3.x * w3.y;\n'
    + '    return max(result, vec3(0.0));\n'
    + '}\n'
    + '\n'
    + 'vec2 fsr2_dilate_velocity(vec2 uv, float curD, out float nearestD) {\n'
    + '    vec2 bestMotion = texture(u_velocity, uv).rg;\n'
    + '    nearestD = curD;\n'
    + '    for (int x = -1; x <= 1; x++) {\n'
    + '        for (int y = -1; y <= 1; y++) {\n'
    + '            if (x == 0 && y == 0) continue;\n'
    + '            vec2 suv = uv + vec2(float(x), float(y)) * u_pixel;\n'
    + '            float d = texture(u_depth, suv).r;\n'
    + '            if (d < nearestD) {\n'
    + '                nearestD = d;\n'
    + '                bestMotion = texture(u_velocity, suv).rg;\n'
    + '            }\n'
    + '        }\n'
    + '    }\n'
    + '    return bestMotion;\n'
    + '}\n'
    + '\n'
    + 'void main() {\n'
    + '    vec3 cur = texture(u_current, v_uv).rgb;\n'
    + '    float curD = texture(u_depth, v_uv).r;\n'
    + '\n'
    + '    if (u_has_history == 0) {\n'
    + '        frag_color = vec4(cur, curD);\n'
    + '        return;\n'
    + '    }\n'
    + '\n'
    + '    vec2 motion = vec2(0.0);\n'
    + '    if (u_has_velocity > 0.5) {\n'
    + '        float dummyD;\n'
    + '        motion = fsr2_dilate_velocity(v_uv, curD, dummyD);\n'
    + '    }\n'
    + '    if (u_has_reproj == 1 && dot(motion, motion) < 1e-10) {\n'
    + '        vec4 clipPos = vec4(v_uv * 2.0 - 1.0, curD * 2.0 - 1.0, 1.0);\n'
    + '        vec4 worldPos = u_inv_view_proj * clipPos;\n'
    + '        if (abs(worldPos.w) > 1e-8) {\n'
    + '            worldPos /= worldPos.w;\n'
    + '            vec4 prevClip = u_prev_view_proj * worldPos;\n'
    + '            if (abs(prevClip.w) > 1e-6) {\n'
    + '                vec2 prevNdc = prevClip.xy / prevClip.w;\n'
    + '                motion = v_uv - (prevNdc * 0.5 + 0.5);\n'
    + '            }\n'
    + '        }\n'
    + '    }\n'
    + '    vec2 prev_uv = v_uv - motion;\n'
    + '\n'
    + '    float velPx = length(motion) / max(u_pixel.x, u_pixel.y);\n'
    + '    float velConfidence = clamp(velPx / 40.0, 0.0, 1.0);\n'
    + '\n'
    + '    vec3 mn = cur;\n'
    + '    vec3 mx = cur;\n'
    + '    vec3 ySum = fsr2_rgb_to_ycocg(cur);\n'
    + '    vec3 ySqSum = ySum * ySum;\n'
    + '    for (int x = -1; x <= 1; x++) {\n'
    + '        for (int y = -1; y <= 1; y++) {\n'
    + '            if (x == 0 && y == 0) continue;\n'
    + '            vec3 c = texture(u_current, v_uv + vec2(float(x), float(y)) * u_pixel).rgb;\n'
    + '            mn = min(mn, c);\n'
    + '            mx = max(mx, c);\n'
    + '            vec3 yc = fsr2_rgb_to_ycocg(c);\n'
    + '            ySum += yc;\n'
    + '            ySqSum += yc * yc;\n'
    + '        }\n'
    + '    }\n'
    + '    vec3 yMean = ySum / 9.0;\n'
    + '    vec3 yVar = max(ySqSum / 9.0 - yMean * yMean, vec3(0.0));\n'
    + '    vec3 yStd = sqrt(yVar);\n'
    + '    float adaptiveGamma = u_variance_gamma * mix(1.0, 0.5, velConfidence);\n'
    + '    vec3 yExtents = max(yStd * adaptiveGamma, vec3(1e-4));\n'
    + '\n'
    + '    vec3 hist = fsr2_history_catmull_rom(u_history, prev_uv, u_size);\n'
    + '    vec3 histY = fsr2_rgb_to_ycocg(hist);\n'
    + '    vec3 histYClipped = fsr2_clip_to_box(histY, yMean, yExtents);\n'
    + '    vec3 histClipped = clamp(fsr2_ycocg_to_rgb(histYClipped), mn, mx);\n'
    + '\n'
    + '    float clipDist = length(histY - histYClipped) / max(length(yStd), 1e-4);\n'
    + '\n'
    + '    float blend = u_stability;\n'
    + '    if (any(lessThan(prev_uv, vec2(0.0))) || any(greaterThan(prev_uv, vec2(1.0)))) {\n'
    + '        blend = 0.0;\n'
    + '    } else {\n'
    + '        float prevD = texture(u_history, prev_uv).a;\n'
    + '        float ddepth = abs(curD - prevD);\n'
    + '        float diso = smoothstep(0.0, max(u_disocclusion, 1e-4), ddepth);\n'
    + '\n'
    + '        if (diso > 0.02) {\n'
    + '            float spatialConfidence = 0.0;\n'
    + '            for (int x = -1; x <= 1; x++) {\n'
    + '                for (int y = -1; y <= 1; y++) {\n'
    + '                    if (x == 0 && y == 0) continue;\n'
    + '                    vec2 nuv = prev_uv + vec2(float(x), float(y)) * u_pixel;\n'
    + '                    float nd = texture(u_history, nuv).a;\n'
    + '                    float ndiso = smoothstep(0.0, max(u_disocclusion, 1e-4), abs(curD - nd));\n'
    + '                    spatialConfidence = max(spatialConfidence, 1.0 - ndiso);\n'
    + '                }\n'
    + '            }\n'
    + '            diso *= (1.0 - spatialConfidence * 0.6);\n'
    + '        }\n'
    + '\n'
    + '        blend = mix(u_stability, 0.0, diso);\n'
    + '        blend = mix(blend, blend * 0.5, clamp(velPx / 200.0, 0.0, 1.0));\n'
    + '        blend = mix(blend, blend * 0.35, clamp(clipDist * 0.5, 0.0, 1.0));\n'
    + '        if (u_has_reactive > 0.5) {\n'
    + '            float reactive = texture(u_reactive, v_uv).r;\n'
    + '            blend *= (1.0 - reactive * 0.85);\n'
    + '        }\n'
    + '    }\n'
    + '\n'
    + '    vec3 result = mix(cur, histClipped, clamp(blend, 0.0, 1.0));\n'
    + '    if (any(isnan(result)) || any(isinf(result))) {\n'
    + '        result = cur;\n'
    + '    }\n'
    + '    frag_color = vec4(result, curD);\n'
    + '}\n'
)
