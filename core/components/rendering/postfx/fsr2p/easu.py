from __future__ import annotations
EASU_FRAG = (
    "\n"
    + chr(35) + 'version 330 core\n'
    + 'uniform sampler2D u_src;\n'
    + 'uniform sampler2D u_depth;\n'
    + 'uniform vec2 u_src_size;\n'
    + 'uniform vec2 u_src_pixel;\n'
    + 'uniform float u_sharpness;\n'
    + 'in vec2 v_uv;\n'
    + 'out vec4 frag_color;\n'
    + '\n'
    + 'vec3 fsr2_catmull_rom(sampler2D tex, vec2 uv, vec2 texSize, vec2 texelSize) {\n'
    + '    vec2 samplePos = uv * texSize;\n'
    + '    vec2 texPos1 = floor(samplePos - 0.5) + 0.5;\n'
    + '    vec2 f = samplePos - texPos1;\n'
    + '    vec2 w0 = f * (-0.5 + f * (1.0 - 0.5 * f));\n'
    + '    vec2 w1 = 1.0 + f * f * (-2.5 + 1.5 * f);\n'
    + '    vec2 w2 = f * (0.5 + f * (2.0 - 1.5 * f));\n'
    + '    vec2 w3 = f * f * (-0.5 + 0.5 * f);\n'
    + '    vec2 w12 = w1 + w2;\n'
    + '    vec2 offset12 = w2 / max(w12, vec2(1e-5));\n'
    + '    vec2 texPos0 = (texPos1 - 1.0) * texelSize;\n'
    + '    vec2 texPos3 = (texPos1 + 2.0) * texelSize;\n'
    + '    vec2 texPos12 = (texPos1 + offset12) * texelSize;\n'
    + '    vec3 result = vec3(0.0);\n'
    + '    result += texture(tex, vec2(texPos0.x, texPos0.y)).rgb * w0.x * w0.y;\n'
    + '    result += texture(tex, vec2(texPos12.x, texPos0.y)).rgb * w12.x * w0.y;\n'
    + '    result += texture(tex, vec2(texPos3.x, texPos0.y)).rgb * w3.x * w0.y;\n'
    + '    result += texture(tex, vec2(texPos0.x, texPos12.y)).rgb * w0.x * w12.y;\n'
    + '    result += texture(tex, vec2(texPos12.x, texPos12.y)).rgb * w12.x * w12.y;\n'
    + '    result += texture(tex, vec2(texPos3.x, texPos12.y)).rgb * w3.x * w12.y;\n'
    + '    result += texture(tex, vec2(texPos0.x, texPos3.y)).rgb * w0.x * w3.y;\n'
    + '    result += texture(tex, vec2(texPos12.x, texPos3.y)).rgb * w12.x * w3.y;\n'
    + '    result += texture(tex, vec2(texPos3.x, texPos3.y)).rgb * w3.x * w3.y;\n'
    + '    return max(result, vec3(0.0));\n'
    + '}\n'
    + '\n'
    + 'float fsr2_luma(vec3 c) {\n'
    + '    return dot(c, vec3(0.299, 0.587, 0.114));\n'
    + '}\n'
    + '\n'
    + 'void main() {\n'
    + '    vec3 base = fsr2_catmull_rom(u_src, v_uv, u_src_size, u_src_pixel);\n'
    + '\n'
    + '    vec3 c00 = texture(u_src, v_uv + vec2(-1.0, -1.0) * u_src_pixel).rgb;\n'
    + '    vec3 c10 = texture(u_src, v_uv + vec2(0.0, -1.0) * u_src_pixel).rgb;\n'
    + '    vec3 c20 = texture(u_src, v_uv + vec2(1.0, -1.0) * u_src_pixel).rgb;\n'
    + '    vec3 c01 = texture(u_src, v_uv + vec2(-1.0, 0.0) * u_src_pixel).rgb;\n'
    + '    vec3 c11 = texture(u_src, v_uv).rgb;\n'
    + '    vec3 c21 = texture(u_src, v_uv + vec2(1.0, 0.0) * u_src_pixel).rgb;\n'
    + '    vec3 c02 = texture(u_src, v_uv + vec2(-1.0, 1.0) * u_src_pixel).rgb;\n'
    + '    vec3 c12 = texture(u_src, v_uv + vec2(0.0, 1.0) * u_src_pixel).rgb;\n'
    + '    vec3 c22 = texture(u_src, v_uv + vec2(1.0, 1.0) * u_src_pixel).rgb;\n'
    + '\n'
    + '    float l00 = fsr2_luma(c00), l10 = fsr2_luma(c10), l20 = fsr2_luma(c20);\n'
    + '    float l01 = fsr2_luma(c01), l11 = fsr2_luma(c11), l21 = fsr2_luma(c21);\n'
    + '    float l02 = fsr2_luma(c02), l12 = fsr2_luma(c12), l22 = fsr2_luma(c22);\n'
    + '\n'
    + '    float gx = (l20 + 2.0 * l21 + l22) - (l00 + 2.0 * l01 + l02);\n'
    + '    float gy = (l02 + 2.0 * l12 + l22) - (l00 + 2.0 * l10 + l20);\n'
    + '    float lumaEdge = clamp(length(vec2(gx, gy)), 0.0, 1.0);\n'
    + '\n'
    + '    float d00 = texture(u_depth, v_uv + vec2(-1.0, -1.0) * u_src_pixel).r;\n'
    + '    float d10 = texture(u_depth, v_uv + vec2(0.0, -1.0) * u_src_pixel).r;\n'
    + '    float d20 = texture(u_depth, v_uv + vec2(1.0, -1.0) * u_src_pixel).r;\n'
    + '    float d01 = texture(u_depth, v_uv + vec2(-1.0, 0.0) * u_src_pixel).r;\n'
    + '    float d11 = texture(u_depth, v_uv).r;\n'
    + '    float d21 = texture(u_depth, v_uv + vec2(1.0, 0.0) * u_src_pixel).r;\n'
    + '    float d02 = texture(u_depth, v_uv + vec2(-1.0, 1.0) * u_src_pixel).r;\n'
    + '    float d12 = texture(u_depth, v_uv + vec2(0.0, 1.0) * u_src_pixel).r;\n'
    + '    float d22 = texture(u_depth, v_uv + vec2(1.0, 1.0) * u_src_pixel).r;\n'
    + '    float dMin = min(min(min(d00, d10), min(d20, d01)), min(min(d11, d21), min(d02, min(d12, d22))));\n'
    + '    float dMax = max(max(max(d00, d10), max(d20, d01)), max(max(d11, d21), max(d02, max(d12, d22))));\n'
    + '    float depthEdge = clamp((dMax - dMin) / max(dMax, 1e-4), 0.0, 1.0);\n'
    + '    depthEdge = smoothstep(0.02, 0.35, depthEdge);\n'
    + '\n'
    + '    float edge = max(lumaEdge, depthEdge);\n'
    + '\n'
    + '    vec3 blurAvg = (c00 + c10 + c20 + c01 + c11 + c21 + c02 + c12 + c22) / 9.0;\n'
    + '    vec3 mn = min(min(min(c00, c10), min(c20, c01)), min(min(c11, c21), min(c02, min(c12, c22))));\n'
    + '    vec3 mx = max(max(max(c00, c10), max(c20, c01)), max(max(c11, c21), max(c02, max(c12, c22))));\n'
    + '\n'
    + '    vec3 sharpened = base + (base - blurAvg) * (lumaEdge * u_sharpness * 2.0);\n'
    + '    sharpened = clamp(sharpened, mn, mx);\n'
    + '\n'
    + '    frag_color = vec4(mix(base, sharpened, edge), 1.0);\n'
    + '}\n'
)
